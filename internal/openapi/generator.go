// Package openapi is the OpenAPI generator of the platform, the protoc-gen-platform-openapi
// plugin of buf. It describes the REST API the way the gateway of the api module serves
// it: proto field names, enums by name, 64-bit integers as strings, every field of a
// response present, requests checked by protovalidate, files over multipart/form-data,
// one error body. The human part of the description stays in the project's base.yaml.
package openapi

