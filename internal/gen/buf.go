const openapiGo = header + `
// Package openapi holds the OpenAPI description generated from the proto files. The api
// module serves it at /openapi.yaml.
package openapi

import "embed"

// FS is the generated description directory.
//
//go:embed *
var FS embed.FS
`

// platformProtoInputs keeps the proto files of the platform out of the project's
// generation: their Go code lives in the platform, and their go_package stays as it is.
const platformProtoInputs = `    - file_option: go_package
      path: platform
`

const bufGenInputs = `inputs:
  - directory: {{dir}}
    exclude_paths:
      - {{dir}}/platform
`

// OpenAPIOptionsPath is the options of the platform's OpenAPI generator under the proto
// folder of the project, written with openapi.generator: platform.
const OpenAPIOptionsPath = "platform/openapi/v1/options.proto"

func apiFiles(f *spec.File, s APISettings) map[string][]byte {
	files := map[string][]byte{
		BufPath:     bufConfig(s),
		BufGenPath:  bufGenConfig(f, s),
		OpenAPIPath: []byte(openapiGo),
	}
	if s.OpenAPI.Generator == OpenAPIPlatform {
		files[s.ProtoPath(OpenAPIOptionsPath)] = []byte(openapipb.Proto)
	}
	return files
}

func bufConfig(s APISettings) []byte {
	var b strings.Builder
	b.WriteString(strings.ReplaceAll(bufYAMLHead, "{{dir}}", s.ProtoDir))
	if s.keepsGnostic() {
		b.WriteString(gnosticDep)
	}
	if deps := s.extraDeps(); len(deps) > 0 {
		b.WriteString("  # From platformgo.yaml.\n")
		for _, d := range deps {
			b.WriteString("  - " + d + "\n")
		}
	}
	b.WriteString(bufYAMLTail)
	if len(s.Buf.BreakingExcept) > 0 {
		b.WriteString("  except:\n")
		for _, rule := range s.Buf.BreakingExcept {
			b.WriteString("    - " + rule + "\n")
		}
	}
	return []byte(b.String())
}

func bufGenConfig(f *spec.File, s APISettings) []byte {
	var deps strings.Builder
	for _, d := range s.extraDeps() {
		name, _, _ := strings.Cut(d, ":")
		deps.WriteString("    - file_option: go_package\n      module: " + name + "\n")
	}
	bufGen := strings.ReplaceAll(bufGenYAML, "{{module}}", f.Project.Module)
	bufGen = strings.Replace(bufGen, "{{deps}}", deps.String(), 1)
	gnostic := ""
	if s.keepsGnostic() {
		gnostic = "    - file_option: go_package\n      module: buf.build/gnostic/gnostic\n"
	}
	bufGen = strings.Replace(bufGen, "{{gnostic}}", gnostic, 1)
	switch s.OpenAPI.Generator {
	case OpenAPIConnect:
		bufGen += connectOpenAPIPlugin
	case OpenAPIPlatform:
		bufGen += platformOpenAPIPlugin
	}
	// The proto files of the platform — the i18n option, the OpenAPI options — are
	// imported, not generated: their Go code is the platform's.
	if _, ok := f.Modules["i18n"]; ok || s.OpenAPI.Generator == OpenAPIPlatform {
		bufGen = strings.Replace(bufGen, "  override:\n", platformProtoInputs+"  override:\n", 1)
		bufGen += strings.ReplaceAll(bufGenInputs, "{{dir}}", s.ProtoDir)
	}
	return []byte(bufGen)
}

// The generators of the OpenAPI description, the openapi.generator option of api.
const (
	OpenAPIConnect  = "connect"  // protoc-gen-connect-openapi, one api/openapi/openapi.yaml
	OpenAPIPlatform = "platform" // protoc-gen-platform-openapi, the platform's own generator
	OpenAPINone     = "none"     // none: the project keeps api/openapi/openapi.yaml itself
)

// APISettings is the section of the api module: where the proto files are, buf
// dependencies and breaking rules on top of the platform's, and who writes the OpenAPI
// description.
type APISettings struct {
	ProtoDir string `yaml:"proto_dir"`
	Buf      struct {
		Deps           []string `yaml:"deps"`
		BreakingExcept []string `yaml:"breaking_except"`
	} `yaml:"buf"`
	OpenAPI struct {
		Generator string `yaml:"generator"`
	} `yaml:"openapi"`
}

// GeneratesOpenAPI reports whether make generate writes api/openapi/openapi.yaml.
func (s APISettings) GeneratesOpenAPI() bool { return s.OpenAPI.Generator != OpenAPINone }

// extraDeps are the dependencies of the project that the platform does not declare
// already, in the order of the file.
func (s APISettings) extraDeps() []string {
	var out []string
	for _, d := range s.Buf.Deps {
		name, _, _ := strings.Cut(d, ":")
		if slices.Contains(s.platformDeps(), name) {
			continue
		}
		out = append(out, d)
	}
	return out
}

var (
	bufDep     = regexp.MustCompile(`^[a-z0-9.-]+\.[a-z]+/[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+(:[A-Za-z0-9_.-]+)?$`)
	breakingID = regexp.MustCompile(`^[A-Z][A-Z0-9_]*$`)
	protoDir   = regexp.MustCompile(`^[A-Za-z0-9_][A-Za-z0-9_./-]*$`)
)

// API reads the section of the api module, with the defaults for what the file leaves
// out.
func API(f *spec.File) (APISettings, error) {
	var s APISettings
	if err := f.DecodeOptions("api", &s); err != nil {
		return APISettings{}, err
	}
	s.ProtoDir = clean(s.ProtoDir)
	var errs []error
	switch {
	case !lock.SafePath(s.ProtoDir) || !protoDir.MatchString(s.ProtoDir):
		errs = append(errs, fmt.Errorf("proto_dir %q must be a folder inside the project, of letters, digits, _ . - and /", s.ProtoDir))
	case within(s.ProtoDir, APIGenDir) || within(s.ProtoDir, "api/openapi"):
		errs = append(errs, fmt.Errorf("proto_dir %q is inside a folder buf writes to, %s or api/openapi", s.ProtoDir, APIGenDir))
	}
	seen := map[string]bool{}
	for _, d := range s.Buf.Deps {
		name, _, _ := strings.Cut(d, ":")
		switch {
		case !bufDep.MatchString(d):
			errs = append(errs, fmt.Errorf("buf.deps: %q is not a buf module such as buf.build/grpc-ecosystem/grpc-gateway", d))
		case seen[name]:
			errs = append(errs, fmt.Errorf("buf.deps: %s is listed twice", name))
		case name != d && slices.Contains(s.platformDeps(), name):
			errs = append(errs, fmt.Errorf("buf.deps: %s is a dependency of the platform, its label is the platform's", name))
		}
		seen[name] = true
	}
	for _, rule := range s.Buf.BreakingExcept {
		if !breakingID.MatchString(rule) {
			errs = append(errs, fmt.Errorf("buf.breaking_except: %q is not a buf rule or category such as FIELD_NO_DELETE", rule))
		}
	}
	if err := errors.Join(errs...); err != nil {
		return APISettings{}, fmt.Errorf("module api: %w", err)
	}
	return s, nil
}

// Tools are the buf plugins the api module pins in go.mod, by the OpenAPI generator: the
// connect plugin for connect, the platform's plugin for platform, neither for none.
func (s APISettings) Tools(tools []registry.Tool, platformVersion string) []registry.Tool {
	if s.OpenAPI.Generator == OpenAPIConnect {
		return tools
	}
	out := make([]registry.Tool, 0, len(tools))
	for _, t := range tools {
		if t.Package != ConnectOpenAPITool {
			out = append(out, t)
		}
	}
	if s.OpenAPI.Generator == OpenAPIPlatform {
		out = append(out, registry.Tool{Module: PlatformModule, Package: PlatformOpenAPITool, Version: platformVersion})
	}
	return out
}

// The OpenAPI plugins as go tool packages.
const (
	ConnectOpenAPITool  = "github.com/sudorandom/protoc-gen-connect-openapi"
	PlatformModule      = "github.com/aidarbn/platform-go"
	PlatformOpenAPITool = PlatformModule + "/cmd/protoc-gen-platform-openapi"
)

// ProtoPath is a file under the proto folder.
func (s APISettings) ProtoPath(rel string) string { return path.Join(s.ProtoDir, rel) }
