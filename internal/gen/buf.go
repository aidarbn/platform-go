package gen

import (
	"strings"

	"github.com/aidarbn/platform-go/internal/spec"
)

// Files of the api module.
const (
	BufPath     = "buf.yaml"
	BufGenPath  = "buf.gen.yaml"
	OpenAPIPath = "api/openapi/openapi.gen.go"

	// APIGenDir is where the Go code of the proto files is generated.
	APIGenDir = "internal/api/gen"
)

const bufYAML = `# Generated by platformgo from platformgo.yaml. Do not edit.
# The API of the project: proto files in proto/, generated with make generate.
version: v2
modules:
  - path: proto
deps:
  - buf.build/googleapis/googleapis
  - buf.build/bufbuild/protovalidate
lint:
  use: [STANDARD]
breaking:
  use: [FILE]
`

// bufGenYAML runs every plugin through go tool, at the versions pinned in go.mod.
// Managed mode sets go_package, so proto files do not repeat the Go import path.
const bufGenYAML = `# Generated by platformgo from platformgo.yaml. Do not edit.
version: v2
managed:
  enabled: true
  disable:
    - file_option: go_package
      module: buf.build/googleapis/googleapis
    - file_option: go_package
      module: buf.build/bufbuild/protovalidate
  override:
    - file_option: go_package_prefix
      value: {{module}}/internal/api/gen
plugins:
  - local: [go, tool, protoc-gen-go]
    out: internal/api/gen
    opt: [paths=source_relative]
  - local: [go, tool, protoc-gen-go-grpc]
    out: internal/api/gen
    opt: [paths=source_relative]
  - local: [go, tool, protoc-gen-grpc-gateway]
    out: internal/api/gen
    opt: [paths=source_relative]
  - local: [go, tool, protoc-gen-connect-openapi]
    out: api/openapi
    strategy: all
    opt:
      # REST paths from google.api.http, validation rules from protovalidate, and
      # descriptions from gnostic annotations. connectrpc stays off: the gateway does
      # not serve Connect paths, so they must not be documented.
      - features=google.api.http;protovalidate;gnostic
      - with-proto-names
      - path=openapi.yaml
`

const openapiGo = header + `
// Package openapi holds the OpenAPI description generated from the proto files. The api
// module serves it at /openapi.yaml.
package openapi

import "embed"

// FS is the generated description directory.
//
//go:embed *
var FS embed.FS
`

// platformProtoInputs keeps the proto files of the platform out of the project's
// generation: their Go code lives in the platform, and their go_package stays as it is.
const platformProtoInputs = `    - file_option: go_package
      path: platform
`

const bufGenInputs = `inputs:
  - directory: proto
    exclude_paths:
      - proto/platform
`

func apiFiles(f *spec.File) map[string][]byte {
	bufGen := strings.ReplaceAll(bufGenYAML, "{{module}}", f.Project.Module)
	if _, ok := f.Modules["i18n"]; ok {
		bufGen = strings.Replace(bufGen, "  override:\n", platformProtoInputs+"  override:\n", 1)
		bufGen += bufGenInputs
	}
	return map[string][]byte{
		BufPath:     []byte(bufYAML),
		BufGenPath:  []byte(bufGen),
		OpenAPIPath: []byte(openapiGo),
	}
}
