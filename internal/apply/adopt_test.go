const withAPI = `schema: 1
project:
  module: example.com/shop-api
modules:
  postgres: {}
  api: {}
`

// foreign is a trimmed layout of a service that was not made by the platform: its own
// compose file, buf configuration and environment example, code and a Makefile.
var foreign = map[string]string{
	gen.ComposePath:               "services:\n  postgres:\n    image: postgres:16\n",
	gen.BufPath:                   "version: v2\nmodules:\n  - path: api\n",
	gen.EnvPath:                   "DB_URL=postgres://localhost/shop\n",
	"cmd/app/main.go":             "package main\n\nfunc main() {}\n",
	"Makefile":                    "build:\n\tgo build ./...\n",
	"db/migrations/0001_init.sql": "-- +goose Up\nCREATE TABLE t (id int);\n",
}

func foreignProject(t *testing.T) string {
	t.Helper()
	dir := project(t, withAPI)
	for path, content := range foreign {
		writeFile(t, dir, path, content)
	}
	return dir
}

func read(t *testing.T, dir, path string) string {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join(dir, path))
	if err != nil {
		t.Fatal(err)
	}
	return string(raw)
}

func TestForeignFileIsAConflict(t *testing.T) {
	dir := foreignProject(t)
	p := build(t, dir)
	want := []string{gen.EnvPath, gen.BufPath, gen.ComposePath}
	slices.Sort(want)
	if got := p.ConflictPaths(); !slices.Equal(got, want) {
		t.Errorf("conflicts = %v, want %v", got, want)
	}
	for _, c := range p.Conflicts {
		if slices.Contains(p.Write, c.Path) {
			t.Errorf("%s is both a conflict and a write", c.Path)
		}
		if string(c.Disk) != foreign[c.Path] || !gen.IsGenerated(c.Generated) {
			t.Errorf("%s: disk %q, generated %q", c.Path, c.Disk, c.Generated)
		}
	}
	if p.UpToDate() {
		t.Error("a plan with conflicts is up to date")
	}

	// Without adopt nothing is written at all.
	if err := p.Execute(); err == nil || !strings.Contains(err.Error(), "--adopt") {
		t.Fatalf("Execute = %v", err)
	}
	for path, content := range foreign {
		if read(t, dir, path) != content {
			t.Errorf("%s was changed", path)
		}
	}
	if exists(dir, gen.ConfigPath) || exists(dir, lock.FileName) {
		t.Error("a refused apply wrote files")
	}
}

// A file the lock records is the platform's even without the mark: apply rewrites it.
func TestFileInLockWithoutMarkIsRewritten(t *testing.T) {
	dir := project(t, withAPI)
	execute(t, dir)
	writeFile(t, dir, gen.BufPath, "version: v2\n# edited, the mark is gone\n")
	p := build(t, dir)
	if len(p.Conflicts) != 0 || !slices.Contains(p.Write, gen.BufPath) {
		t.Fatalf("conflicts = %v, write = %v", p.ConflictPaths(), p.Write)
	}
	execute(t, dir)
	if !gen.IsGenerated([]byte(read(t, dir, gen.BufPath))) {
		t.Error("buf.yaml was not rewritten")
	}
}

// A file with the mark is the platform's even when the lock does not know it, as for a
// project whose lock was lost.
func TestMarkedFileOutsideLockIsRewritten(t *testing.T) {
	dir := project(t, withAPI)
	writeFile(t, dir, gen.BufPath, "# Generated by platformgo from platformgo.yaml. Do not edit.\nversion: v1\n")
	if p := build(t, dir); len(p.Conflicts) != 0 || !slices.Contains(p.Write, gen.BufPath) {
		t.Errorf("conflicts = %v, write = %v", p.ConflictPaths(), p.Write)
	}
}

func TestForceTakesTheGeneratedVersion(t *testing.T) {
	dir := foreignProject(t)
	p := build(t, dir)
	if err := p.Force("./"+gen.BufPath, gen.ComposePath); err != nil {
		t.Fatal(err)
	}
	if got := p.ConflictPaths(); !slices.Equal(got, []string{gen.EnvPath}) {
		t.Fatalf("conflicts left = %v", got)
	}
	if err := p.Force("cmd/app/main.go"); err == nil || !strings.Contains(err.Error(), "not a conflict") {
		t.Errorf("Force of a path that is not a conflict = %v", err)
	}
	if err := p.Force(gen.EnvPath); err != nil {
		t.Fatal(err)
	}
	if err := p.Execute(); err != nil {
		t.Fatal(err)
	}
	for _, path := range []string{gen.BufPath, gen.ComposePath, gen.EnvPath} {
		if !gen.IsGenerated([]byte(read(t, dir, path))) {
			t.Errorf("%s was not taken from generation", path)
		}
	}
	if !build(t, dir).UpToDate() {
		t.Error("not up to date after forcing every conflict")
	}
}

func TestAdoptWritesOnlyNewFiles(t *testing.T) {
	dir := foreignProject(t)
	p := build(t, dir)
	created, report, err := p.Adopt()
	if err != nil {
		t.Fatal(err)
	}
	for path, content := range foreign {
		if read(t, dir, path) != content {
			t.Errorf("%s was changed", path)
		}
	}
	for _, path := range []string{gen.ConfigPath, gen.ModulesPath, gen.MigrationsPath, gen.SqlcPath, gen.BufGenPath, gen.OpenAPIPath, gen.OpenAPIBasePath} {
		if !slices.Contains(created, path) || !exists(dir, path) {
			t.Errorf("%s was not created: %v", path, created)
		}
	}
	if !report {
		t.Fatal("no report")
	}
	text := read(t, dir, apply.AdoptReport)
	for _, want := range []string{
		"## Conflicts", "### docker-compose.yml", "docker-compose.override.yml", "### buf.yaml", "proto_dir",
		"-    image: postgres:16", "+    image: postgres:18-alpine", "--- docker-compose.yml (project)",
	} {
		if !strings.Contains(text, want) {
			t.Errorf("report lacks %q:\n%s", want, text)
		}
	}

	// The lock leaves the conflicts out, so a later apply still refuses them.
	l, err := lock.Read(dir)
	if err != nil {
		t.Fatal(err)
	}
	for _, path := range p.ConflictPaths() {
		if slices.Contains(l.Generated, path) {
			t.Errorf("the lock claims %s", path)
		}
	}
	again := build(t, dir)
	if len(again.Conflicts) != 3 || len(again.Create) != 0 || again.UpToDate() {
		t.Errorf("after adopt: conflicts %v, create %v", again.ConflictPaths(), again.Create)
	}

	// Once the conflicts are gone apply finishes the job.
	for _, path := range again.ConflictPaths() {
		if err := os.Remove(filepath.Join(dir, path)); err != nil {
			t.Fatal(err)
		}
	}
	execute(t, dir)
	if !build(t, dir).UpToDate() {
		t.Error("not up to date after the conflicts were resolved")
	}
}

// Without conflicts adopt still changes nothing that exists, and lists what apply will.
func TestAdoptReportsWhatIsLeft(t *testing.T) {
	dir := project(t, withAPI)
	execute(t, dir)
	writeFile(t, dir, gen.ModulesPath, "// Code generated by platformgo from platformgo.yaml. DO NOT EDIT.\npackage main\n")
	p := build(t, dir)
	_, report, err := p.Adopt()
	if err != nil || !report {
		t.Fatalf("Adopt: %v, report %v", err, report)
	}
	text := read(t, dir, apply.AdoptReport)
	if strings.Contains(text, "## Conflicts") || !strings.Contains(text, "write `"+gen.ModulesPath+"`") {
		t.Errorf("report:\n%s", text)
	}
	if !strings.HasSuffix(read(t, dir, gen.ModulesPath), "package main\n") {
		t.Error("an existing file was rewritten")
	}

	clean := project(t, withAPI)
	execute(t, clean)
	if _, report, err := build(t, clean).Adopt(); err != nil || report || exists(clean, apply.AdoptReport) {
		t.Errorf("an applied project got a report: %v, %v", report, err)
	}
}

// Every generated file carries the mark of platformgo on its first line, except the
// formats that cannot: those are recognised by the lock only.
func TestEveryGeneratedFileIsMarked(t *testing.T) {
	dir := project(t, `schema: 1
project:
  module: example.com/shop-api
modules:
  postgres: {}
  admin: {}
  api: {}
  enums: {}
  i18n: {}
  monitoring: {}
  rbac: {}
  river: {}
  s3: {}
  settings: {}
  web: {}
`)
	execute(t, dir)
	f, err := spec.Load(filepath.Join(dir, spec.FileName))
	if err != nil {
		t.Fatal(err)
	}
	files, err := gen.Files(dir, f)
	if err != nil {
		t.Fatal(err)
	}
	unmarked := []string{
		gen.I18nProtoPath,                             // the very file kit/i18nx is generated from
		"proto/" + gen.OpenAPIOptionsPath,             // the very file kit/openapipb is generated from
		"monitoring/grafana/dashboards/platform.json", // JSON has no comments
	}
	for path, content := range files {
		if !gen.IsGenerated(content) && !slices.Contains(unmarked, path) {
			t.Errorf("%s has no mark: a project that has it outside the lock would see a conflict", path)
		}
	}
}

// adopt records only what it did: the platform version, the tools and the generated
// files waiting for deletion stay in the lock, so apply still does that work later.
func TestAdoptKeepsPendingWorkInTheLock(t *testing.T) {
	dir := project(t, withSettings)
	execute(t, dir)
	before, err := lock.Read(dir)
	if err != nil {
		t.Fatal(err)
	}
	before.Platform = "v0.1.0"
	before.Tools = append(before.Tools, "example.com/tool/cmd/tool")
	if err := lock.Write(dir, before); err != nil {
		t.Fatal(err)
	}

	// settings goes away, api comes with a buf.yaml of the project's own.
	writeFile(t, dir, spec.FileName, strings.Replace(withSettings, "  settings: {}\n", "  api: {}\n", 1))
	writeFile(t, dir, gen.BufPath, "version: v2\n")
	p := build(t, dir)
	if !slices.Contains(p.Delete, gen.SettingsPath) || len(p.Conflicts) != 1 {
		t.Fatalf("delete = %v, conflicts = %v", p.Delete, p.ConflictPaths())
	}
	if _, _, err := p.Adopt(); err != nil {
		t.Fatal(err)
	}
	if !exists(dir, gen.SettingsPath) {
		t.Error("adopt deleted a file")
	}
	after, err := lock.Read(dir)
	if err != nil {
		t.Fatal(err)
	}
	if after.Platform != "v0.1.0" || !slices.Equal(after.Tools, slices.Sorted(slices.Values(before.Tools))) || !slices.Equal(after.Modules, before.Modules) {
		t.Errorf("lock after adopt = %+v, before %+v", after, before)
	}
	if !slices.Contains(after.Generated, gen.SettingsPath) || !slices.Contains(after.Generated, gen.BufGenPath) || slices.Contains(after.Generated, gen.BufPath) {
		t.Errorf("generated after adopt = %v", after.Generated)
	}
	text := read(t, dir, apply.AdoptReport)
	if !strings.Contains(text, "delete `"+gen.SettingsPath+"`") {
		t.Errorf("report:\n%s", text)
	}

	// The conflict resolved, apply deletes what the removed module left.
	if err := os.Remove(filepath.Join(dir, gen.BufPath)); err != nil {
		t.Fatal(err)
	}
	p = execute(t, dir)
	if !slices.Contains(p.Delete, gen.SettingsPath) || exists(dir, gen.SettingsPath) {
		t.Errorf("apply after adopt did not delete %s: %v", gen.SettingsPath, p.Delete)
	}
}

func TestAdoptWritesForcedConflicts(t *testing.T) {
	dir := foreignProject(t)
	p := build(t, dir)
	if err := p.Force(gen.ComposePath); err != nil {
		t.Fatal(err)
	}
	created, _, err := p.Adopt()
	if err != nil {
		t.Fatal(err)
	}
	if !slices.Contains(created, gen.ComposePath) || !gen.IsGenerated([]byte(read(t, dir, gen.ComposePath))) {
		t.Errorf("the forced file was not written: %v", created)
	}
	if read(t, dir, gen.BufPath) != foreign[gen.BufPath] {
		t.Error("a conflict that was not forced was written")
	}
	l, _ := lock.Read(dir)
	if !slices.Contains(l.Generated, gen.ComposePath) || slices.Contains(l.Generated, gen.BufPath) {
		t.Errorf("lock generated = %v", l.Generated)
	}
}

// A report of an earlier adopt goes once nothing is left for a person.
func TestAdoptRemovesAnOldReport(t *testing.T) {
	dir := project(t, withAPI)
	execute(t, dir)
	writeFile(t, dir, apply.AdoptReport, "# old\n")
	if _, report, err := build(t, dir).Adopt(); err != nil || report {
		t.Fatalf("Adopt: report %v, %v", report, err)
	}
	if exists(dir, apply.AdoptReport) {
		t.Error("the old report stayed")
	}
}
