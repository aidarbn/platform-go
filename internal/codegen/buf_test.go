const pbFile = "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage ordersv1\n"

// fakeBuf behaves like buf: generate writes the Go code and the OpenAPI description under
// the --output directory, dep update writes buf.lock.
func fakeBuf(t *testing.T, pb string) *[][]string {
	t.Helper()
	var calls [][]string
	orig := codegen.GoCommand
	t.Cleanup(func() { codegen.GoCommand = orig })
	codegen.GoCommand = func(_ context.Context, dir string, _ io.Writer, args ...string) error {
		calls = append(calls, args)
		switch {
		case slices.Contains(args, "update"):
			write(t, dir, "buf.lock", "version: v2\n")
		case slices.Contains(args, "generate"):
			base := dir
			if i := slices.Index(args, "--output"); i >= 0 {
				base = args[i+1]
			}
			write(t, base, "internal/api/gen/orders/v1/orders.pb.go", pb)
			write(t, base, "api/openapi/openapi.yaml", "openapi: 3.1.0\n")
		}
		return nil
	}
	return &calls
}

func TestBufGenerates(t *testing.T) {
	dir := t.TempDir()
	calls := fakeBuf(t, pbFile)
	write(t, dir, "proto/orders/v1/orders.proto", `syntax = "proto3";`)
	write(t, dir, "internal/api/gen/removed/v1/removed.pb.go", pbFile)

	if err := codegen.Buf(context.Background(), dir, codegen.DefaultAPI, io.Discard); err != nil {
		t.Fatalf("Buf: %v", err)
	}
	// The dependencies are resolved once, then the code is generated.
	if len(*calls) != 2 || !slices.Contains((*calls)[0], "update") || !slices.Contains((*calls)[1], "generate") {
		t.Errorf("calls = %v", *calls)
	}
	if exists(dir, "internal/api/gen/removed/v1/removed.pb.go") || exists(dir, "internal/api/gen/removed") {
		t.Error("code of a removed proto file stayed")
	}
	if !exists(dir, "internal/api/gen/orders/v1/orders.pb.go") || !exists(dir, "api/openapi/openapi.yaml") {
		t.Error("the fresh code is missing")
	}

	// buf.lock exists now: no second dep update.
	*calls = nil
	if err := codegen.Buf(context.Background(), dir, codegen.DefaultAPI, io.Discard); err != nil {
		t.Fatalf("Buf: %v", err)
	}
	if len(*calls) != 1 {
		t.Errorf("calls = %v", *calls)
	}
}

