package gen_test

import (
	"strings"
	"testing"

	"go.yaml.in/yaml/v3"

	"github.com/aidarbn/platform-go/internal/gen"
)

type composeFile struct {
	Name     string                    `yaml:"name"`
	Services map[string]map[string]any `yaml:"services"`
	Volumes  map[string]any            `yaml:"volumes"`
}

func parseCompose(t *testing.T, raw []byte) composeFile {
	t.Helper()
	var c composeFile
	if err := yaml.Unmarshal(raw, &c); err != nil {
		t.Fatalf("docker-compose.yml is not valid YAML: %v\n%s", err, raw)
	}
	return c
}

func TestComposeHasModuleServices(t *testing.T) {
	files, err := gen.Wiring(mustParse(t, withSettings))
	if err != nil {
		t.Fatalf("Wiring: %v", err)
	}

	raw := files[gen.ComposePath]
	if !strings.HasPrefix(string(raw), "# Generated by platformgo") {
		t.Errorf("no generated header:\n%s", raw)
	}

	c := parseCompose(t, raw)
	if c.Name != "shop-api" {
		t.Errorf("name = %q", c.Name)
	}
	pg, ok := c.Services["postgres"]
	if !ok {
		t.Fatalf("no postgres service: %+v", c.Services)
	}
	if !strings.HasPrefix(pg["image"].(string), "postgres:") {
		t.Errorf("image = %v", pg["image"])
	}
	if _, ok := pg["healthcheck"]; !ok {
		t.Error("postgres has no healthcheck: make up could not wait for it")
	}
	if _, ok := c.Volumes["postgres-data"]; !ok {
		t.Errorf("volumes = %+v", c.Volumes)
	}
	// Only modules with a service add one.
	if len(c.Services) != 1 {
		t.Errorf("services = %v", c.Services)
	}
}

// Removing the last module with a service must remove the service too, so the file is
// generated even when it is empty.
func TestComposeWithoutServices(t *testing.T) {
	files, err := gen.Wiring(mustParse(t, "schema: 1\nproject:\n  module: github.com/x/My.App\n"))
	if err != nil {
		t.Fatalf("Wiring: %v", err)
	}
	c := parseCompose(t, files[gen.ComposePath])
	if len(c.Services) != 0 || c.Volumes != nil {
		t.Errorf("compose = %+v", c)
	}
	if c.Name != "my-app" {
		t.Errorf("the project name must be what docker compose accepts: %q", c.Name)
	}
}
